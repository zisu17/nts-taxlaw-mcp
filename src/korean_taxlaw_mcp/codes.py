CASE_KIND: dict[str, str] = {"01": "행정", "02": "민사", "03": "형사", "ZZ": "해당없음"}

_BLANK_CODES = {"", "ZZ", "ZZZZZZZZZZZZZZZZZZ"}


def is_blank_code(value: Any) -> bool:
    """값이 "없음" 자리표시자인지. 사이트는 빈 값을 ZZ 로 채운다."""
    if value is None:
        return True
    return str(value).strip() in _BLANK_CODES


def decode_or_none(table: dict[str, str], code: Any) -> str | None:
    if is_blank_code(code):
        return None
    return table.get(str(code).strip())
